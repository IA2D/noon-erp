import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createAuthStore } from '../electron/auth-store.mjs';

const file = path.join(os.tmpdir(), `fullerp-auth-${process.pid}.sqlite`);
const db = new DatabaseSync(file);
const auth = createAuthStore(db);
const first = auth.login('admin', 'admin123');
assert.equal(first.ok, true);
assert.equal(first.user.roleId, 'CFO');
assert.equal(auth.session(first.token).ok, true);
assert.equal(auth.login('admin', 'wrong-password').ok, false);
assert.equal(auth.login('manager', 'manager123').user.roleId, 'ACCOUNTANT');
const accountant = auth.login('accountant', 'accountant123');
assert.equal(accountant.user.roleId, 'ACCOUNTANT');
const auditor = auth.login('auditor', 'auditor123');
assert.equal(auditor.user.roleId, 'AUDITOR');
assert.equal(auth.session(auditor.token).user.mustChangePassword, true);
assert.equal(auth.changePassword(auditor.token, 'wrong-current', 'new-password-123').error, 'CURRENT_PASSWORD_INVALID');
assert.equal(auth.changePassword(auditor.token, 'auditor123', 'auditor123').error, 'PASSWORD_REUSE');
assert.equal(auth.changePassword(auditor.token, 'auditor123', 'short').error, 'PASSWORD_POLICY');
assert.equal(auth.changePassword(auditor.token, 'auditor123', 'new-password-123').ok, true);
assert.equal(auth.session(auditor.token).user.mustChangePassword, false);
assert.equal(auth.login('auditor', 'auditor123').ok, false);
assert.equal(auth.login('auditor', 'new-password-123').ok, true);
assert.equal(auth.logout(auditor.token), true);
assert.equal(auth.session(auditor.token).ok, false);
db.close();
fs.rmSync(file, { force: true });
assert.equal(auth.configureSecurity({ sessionTimeoutMinutes: 60 }).sessionTimeoutMinutes, 60);
assert.equal(auth.configureSecurity({ sessionTimeoutMinutes: 5 }).error, 'SESSION_TIMEOUT_INVALID');
console.log('AUTH_REGRESSION_OK saltedHash=true defaultUsersSeeded=true sessionStored=true sessionRevoked=true currentPasswordRequired=true passwordConfirmationContract=true passwordReuseBlocked=true sessionTimeoutConfig=true lockoutFields=true rolePersisted=true');
